"""Runtime configuration for the CTAID POC demo.

Every setting has a safe local default. Cloud wiring (Garage S3, Convex) is
optional and only switches on when the matching environment variables are set,
so the app is fully functional on a laptop with no external services.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
DEFAULT_DATASET = DATA_DIR / "synthetic_features.csv"
MODELS_DIR = ROOT / "models"


def load_dotenv(path: Path | None = None) -> None:
    """Load a simple KEY=VALUE .env file without adding a dependency.

    Existing environment variables win, so a container or CI setting is never
    overwritten by a stray local file.
    """
    candidate = Path(path) if path else ROOT / ".env"
    if not candidate.is_file():
        return
    for line in candidate.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, value = stripped.split("=", 1)
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        if key and key not in os.environ:
            os.environ[key] = value


load_dotenv()

STATE_DIR = Path(os.environ.get("CTAID_STATE_DIR") or ROOT / "var")
