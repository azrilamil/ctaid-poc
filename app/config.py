def _env(name: str, default: str = "") -> str:
    return os.environ.get(name, default).strip()


@dataclass(frozen=True)
class ObjectStoreConfig:
    """Garage S3 settings, all optional."""

    endpoint: str = ""
    bucket: str = "ctaid-poc-demo"
    region: str = "garage"
    access_key: str = ""
    secret_key: str = ""

    @property
    def enabled(self) -> bool:
        return bool(self.endpoint and self.access_key and self.secret_key)

    @classmethod
    def from_env(cls) -> ObjectStoreConfig:
        return cls(
            endpoint=_env("S3_ENDPOINT"),
            bucket=_env("S3_BUCKET", "ctaid-poc-demo"),
            region=_env("S3_REGION", "garage"),
            access_key=_env("S3_ACCESS_KEY_ID") or _env("AWS_ACCESS_KEY_ID"),
            secret_key=_env("S3_SECRET_ACCESS_KEY") or _env("AWS_SECRET_ACCESS_KEY"),
        )


@dataclass(frozen=True)
class ConvexConfig:
    """Convex deployment settings, all optional."""

    url: str = ""
    token: str = ""
    timeout_s: float = 5.0

    @property
    def enabled(self) -> bool:
        return bool(self.url)

    @classmethod
    def from_env(cls) -> ConvexConfig:
        return cls(url=_env("CONVEX_URL"), token=_env("CONVEX_DEPLOY_KEY") or _env("CONVEX_TOKEN"))


@dataclass(frozen=True)
class Settings:
    dataset_path: Path
    models_dir: Path
    state_dir: Path
    storage: ObjectStoreConfig
    convex: ConvexConfig
    random_seed: int = 42

    @classmethod
    def load(cls) -> Settings:
        dataset = Path(_env("CTAID_DATA_PATH") or DEFAULT_DATASET)
        models = Path(_env("CTAID_MODELS_DIR") or MODELS_DIR)
        state = Path(_env("CTAID_STATE_DIR") or STATE_DIR)
        return cls(
            dataset_path=dataset,
            models_dir=models,
            state_dir=state,
            storage=ObjectStoreConfig.from_env(),
            convex=ConvexConfig.from_env(),
        )
