"""Home page."""

from __future__ import annotations

import streamlit as st

from app import charts
from app.schema import CLASS_DESCRIPTIONS, CLASS_LABELS, FEATURE_NAMES, RECORD_ID_COLUMN
from app.state import current_summary, dataset
from app.theme import card, chips, footer, hero, page_header, section, stat


def render() -> None:
    frame = dataset()
    info = current_summary()

    page_header(
        "Research demo",
        "Computed Tomography Artificial Intelligence Detection for Atherosclerosis "
        "<span>(CTAID-A)</span>",
        "A working proof of concept for a CT feature research pipeline: a synthetic "
        "texture feature table, four trainable classifiers, explainable metrics, and a "
        "prediction screen. Everything runs on data this project generates itself.",
    )
    hero()

    cols = st.columns(4)
    with cols[0]:
        stat("Synthetic rows", f"{info['rows']:,}", f"{info['records']:,} records, 3 vessels each")
    with cols[1]:
        stat("Feature columns", f"{info['feature_count']}", "Texture, shape and intensity features")
    with cols[2]:
        stat("Pattern classes", "4", "Invented labels, never a clinical finding")
    with cols[3]:
        stat("Models available", "4", "Logistic, forest, SVM, boosting")

    section("What this demo shows", "Four pages, one honest workflow from table to prediction.")
    col_a, col_b, col_c, col_d = st.columns(4)
    with col_a:
        card(
            "Data Exploration",
            "Filter the synthetic table, read descriptive statistics, plot any feature "
            "against its pattern class, and inspect a correlation heatmap.",
        )
    with col_b:
        card(
            "Model Training",
            "Select one or more classifiers, train them for real on the synthetic set, and "
            "compare accuracy, precision, recall, F1 and ROC AUC.",
        )
    with col_c:
        card(
            "Evaluation",
            "Per class classification report, confusion matrix, one versus rest ROC curves "
            "and feature importance from the fitted model itself.",
        )
    with col_d:
        card(
            "Prediction",
            "Score a row from a slider form, a generated sample pattern, or a small uploaded "
            "CSV. Class probabilities are shown with the demo disclaimer.",
        )

    section("The data", "Generated by scripts/generate_synthetic_data.py with a fixed seed.")
    left, right = st.columns([1.25, 1])
    with left:
        st.plotly_chart(charts.class_balance(frame), width="stretch", theme=None)
    with right:
        st.markdown(
            f"The table holds **{info['rows']:,} rows** across **{info['records']:,} synthetic "
            f"records**, {info['feature_count']} feature columns, plus `{RECORD_ID_COLUMN}`, "
            "`Vessel` and `Pattern`. Columns use names and value ranges from a published "
            "design brief; every value is drawn fresh from those ranges.",
        )
        chips(["Fresh synthetic rows", "Fixed seed", "No identifiers", "No real scans"])
        st.markdown(
            "Class labels stay neutral on purpose. The demo calls them Pattern A to Pattern D "
            "and never assigns a clinical meaning to them.",
        )

    section("Pattern classes", "Four invented groups, described only by their synthetic shape.")
    class_cols = st.columns(4)
    for position, class_id in enumerate(sorted(CLASS_LABELS)):
        with class_cols[position]:
            count = info["class_counts"].get(str(class_id), info["class_counts"].get(class_id, 0))
            card(f"{CLASS_LABELS[class_id]}", f"{CLASS_DESCRIPTIONS[class_id]}<br><br>{count:,} rows")

    section("Privacy", "What is and is not in this repository.")
    privacy_left, privacy_right = st.columns(2)
    with privacy_left:
        st.markdown(
            "**Included:** an original data generator, the CSV it produces, training code, "
            "tests, and documentation.\n\n"
            "**Not included:** clinical images, patient records, private research tables, "
            "third party photographs, or credentials of any kind. The illustration on this "
            "page is generated by `app/artwork.py`."
        )
    with privacy_right:
        st.markdown(
            "Metadata and trained artifacts are kept by a storage layer that runs "
            "inside the demo. Optional cloud wiring switches on only when the matching "
            "environment variables exist, so the demo is complete offline and resets on "
            "a schedule."
        )
        st.markdown(
            f"Feature columns in play: `{FEATURE_NAMES[0]}`, `{FEATURE_NAMES[1]}`, "
            f"`{FEATURE_NAMES[2]}`, and {len(FEATURE_NAMES) - 3} more."
        )

    section("Where to go next")
    st.markdown(
        "- **Data Exploration** to see the table, distributions and correlations.\n"
        "- **Model Training** to fit a model and read real held out metrics.\n"
        "- **Prediction** to score a case and see class probabilities."
    )

    footer()
