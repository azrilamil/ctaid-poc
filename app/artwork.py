"""Original hero artwork for the CTAID POC demo.

The illustration is generated by this module at run time and written to
``app/assets/hero_heart_lungs.svg``. It is an original geometric composition
(lungs, heart, vessel trace, scan rings) drawn by this project, released under
the repository MIT license. No stock photo, no third party asset.
"""

from __future__ import annotations

from pathlib import Path

from app.config import ASSETS_DIR

WIDTH = 1200
HEIGHT = 420


def build_svg() -> str:
    """Return the SVG source for the hero illustration."""
    parts: list[str] = []
    parts.append(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}" '
        f'width="{WIDTH}" height="{HEIGHT}" role="img" '
        'aria-label="Stylised illustration of lungs and a heart inside a CT scan field">'
    )
    parts.append("<title>Lungs and heart inside a CT scan field</title>")
    parts.append(
        "<desc>Original geometric illustration generated by app/artwork.py for the CTAID POC demo. "
        "Synthetic data only, not a medical tool.</desc>"
    )
    parts.append(
        """
<defs>
  <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0%" stop-color="#0A1626"/>
    <stop offset="55%" stop-color="#0D1E33"/>
    <stop offset="100%" stop-color="#0A1420"/>
  </linearGradient>
  <linearGradient id="lung" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0%" stop-color="#7FB6E8" stop-opacity="0.55"/>
    <stop offset="100%" stop-color="#3D6EA8" stop-opacity="0.30"/>
  </linearGradient>
  <linearGradient id="heart" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0%" stop-color="#FF8A6B"/>
    <stop offset="100%" stop-color="#C4402F"/>
  </linearGradient>
  <radialGradient id="glow" cx="50%" cy="50%" r="50%">
    <stop offset="0%" stop-color="#5AC8FA" stop-opacity="0.35"/>
    <stop offset="100%" stop-color="#5AC8FA" stop-opacity="0"/>
  </radialGradient>
  <linearGradient id="vessel" x1="0" y1="0" x2="1" y2="0">
    <stop offset="0%" stop-color="#5AC8FA" stop-opacity="0.15"/>
    <stop offset="45%" stop-color="#8FE3FF" stop-opacity="0.95"/>
    <stop offset="100%" stop-color="#5AC8FA" stop-opacity="0.15"/>
  </linearGradient>
</defs>
"""
    )
    parts.append(f'<rect width="{WIDTH}" height="{HEIGHT}" rx="28" fill="url(#bg)"/>')

    # CT field rings, left of centre.
    parts.append('<g opacity="0.55" stroke="#20344F" fill="none">')
    for index, radius in enumerate((150, 190, 232, 276)):
        parts.append(f'<circle cx="600" cy="212" r="{radius}" stroke-width="{1.4 - index * 0.2:.1f}"/>')
    parts.append("</g>")
    parts.append('<ellipse cx="600" cy="212" rx="300" ry="172" fill="url(#glow)"/>')

    # Scanning arc.
    parts.append(
        '<path d="M 330 300 A 300 180 0 0 1 870 300" stroke="#2F4A6B" stroke-width="2" '
        'stroke-dasharray="7 11" fill="none" opacity="0.7"/>'
    )

    # Lungs.
    parts.append(
        '<path d="M 566 96 C 520 108, 486 152, 482 214 C 478 274, 508 322, 560 330 '
        'C 588 334, 598 312, 598 268 L 598 122 C 598 100, 586 92, 566 96 Z" '
        'fill="url(#lung)" stroke="#8FC7F2" stroke-opacity="0.55" stroke-width="2"/>'
    )
    parts.append(
        '<path d="M 634 96 C 680 108, 714 152, 718 214 C 722 274, 692 322, 640 330 '
        'C 612 334, 602 312, 602 268 L 602 122 C 602 100, 614 92, 634 96 Z" '
        'fill="url(#lung)" stroke="#8FC7F2" stroke-opacity="0.55" stroke-width="2"/>'
    )

    # Bronchial tree.
    parts.append(
        '<g stroke="#A9D6F7" stroke-opacity="0.75" fill="none" stroke-linecap="round" stroke-width="3">'
        '<path d="M 600 84 L 600 168"/>'
        '<path d="M 600 118 L 560 152"/><path d="M 600 118 L 640 152"/>'
        '<path d="M 560 152 L 534 196"/><path d="M 640 152 L 666 196"/>'
        '<path d="M 600 168 L 578 214"/><path d="M 600 168 L 622 214"/>'
        '</g>'
    )

    # Heart with an accent vessel running across it.
    parts.append(
        '<path d="M 600 232 C 570 208, 536 226, 536 258 C 536 296, 578 318, 600 340 '
        'C 622 318, 664 296, 664 258 C 664 226, 630 208, 600 232 Z" '
        'fill="url(#heart)" opacity="0.94"/>'
    )
    parts.append(
        '<path d="M 548 262 C 578 250, 620 276, 654 254" stroke="#FFD9CC" stroke-opacity="0.75" '
        'stroke-width="3.2" fill="none" stroke-linecap="round"/>'
    )

    # Vessel trace crossing the composition.
    parts.append(
        '<path d="M 120 258 C 250 258, 268 176, 396 176 C 470 176, 470 250, 540 250" '
        'stroke="url(#vessel)" stroke-width="4" fill="none" stroke-linecap="round"/>'
    )
    parts.append(
        '<path d="M 690 262 C 780 262, 800 196, 902 196 C 1000 196, 1010 250, 1080 250" '
        'stroke="url(#vessel)" stroke-width="4" fill="none" stroke-linecap="round"/>'
    )
    for cx, cy, radius in ((396, 176, 5.0), (902, 196, 5.0), (600, 240, 4.0)):
        parts.append(f'<circle cx="{cx}" cy="{cy}" r="{radius}" fill="#8FE3FF" opacity="0.9"/>')

    # Data ticks, a quiet nod to the measurement layer.
    parts.append('<g stroke="#3B587A" stroke-width="2" opacity="0.8">')
    for index in range(22):
        x = 92 + index * 46
        height = 16 if index % 3 else 30
        parts.append(f'<line x1="{x}" y1="{HEIGHT - 44}" x2="{x}" y2="{HEIGHT - 44 - height}"/>')
    parts.append("</g>")
    parts.append(
        '<text x="92" y="52" fill="#7F95B3" font-family="Inter, Segoe UI, Arial, sans-serif" '
        'font-size="17" letter-spacing="4.4">SYNTHETIC PATTERN FIELD</text>'
    )
    parts.append(
        '<text x="92" y="78" fill="#4F6787" font-family="Inter, Segoe UI, Arial, sans-serif" '
        'font-size="13" letter-spacing="1.6">Generated illustration, not a scan of a person</text>'
    )
    parts.append("</svg>")
    return "\n".join(parts)


def hero_path() -> Path:
    return ASSETS_DIR / "hero_heart_lungs.svg"


def ensure_hero() -> Path:
    """Write the hero SVG if missing, then return its path."""
    path = hero_path()
    if not path.is_file():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(build_svg(), encoding="utf-8")
    return path


if __name__ == "__main__":
    written = ensure_hero()
    print(f"wrote {written} ({written.stat().st_size} bytes)")
